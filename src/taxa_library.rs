/// Score a `DetectedCallEvent` against all domain-matching species profiles using normalized
/// squared Mahalanobis feature distance (`Fc`, `Fmax`, `Fmin`, `Dur`, topology & harmonic bonus).
pub fn classify_call_event(ev: &DetectedCallEvent) -> (Vec<TaxonMatch>, Option<String>) {
    let mut scored: Vec<(f64, &SpeciesAcousticProfile, f64)> = Vec::new();

    for sp in reference_species_catalog()
        .iter()
        .filter(|p| p.domain == ev.domain)
    {
        let z_fc = (ev.f_char_khz - sp.fc_mean_khz) / sp.fc_sd_khz.max(0.1);
        let z_fmax = (ev.f_max_khz - sp.fmax_mean_khz) / sp.fmax_sd_khz.max(0.1);
        let z_fmin = (ev.f_min_khz - sp.fmin_mean_khz) / sp.fmin_sd_khz.max(0.1);
        let z_dur = (ev.duration_ms - sp.dur_mean_ms) / sp.dur_sd_ms.max(0.5);

        let mut d2 = 1.6 * z_fc * z_fc + 0.8 * z_fmax * z_fmax + 1.0 * z_fmin * z_fmin + 0.7 * z_dur * z_dur;

        // Topology alignment adjustment
        if ev.topology != sp.preferred_topology {
            d2 += 2.2;
        }
        // Whisper-bat 2nd harmonic cue (`Corynorhinus townsendii`)
        if sp.expect_strong_2nd_harmonic {
            if ev.harmonic_2nd_rel_db > -9.0 {
                d2 *= 0.45;
            } else {
                d2 += 4.5;
            }
        }
        let raw_weight = (-0.5 * d2).exp().max(1e-9);
        scored.push((raw_weight, sp, d2));
    }

    scored.sort_by(|a, b| b.0.total_cmp(&a.0));
    let total_w: f64 = scored.iter().map(|x| x.0).sum::<f64>().max(1e-12);

    let top_matches: Vec<TaxonMatch> = scored
        .iter()
        .take(3)
        .map(|(w, sp, d2)| TaxonMatch {
            code: sp.code.to_string(),
            common_name: sp.common_name.to_string(),
            scientific_name: sp.scientific_name.to_string(),
            probability: (*w / total_w).clamp(0.0, 1.0),
            mahalanobis_d2: *d2,
            citation_url: sp.citation_url.to_string(),
        })
        .collect();

    // Flag NABat / NFC sympatric ambiguity couplet when top-2 margin < 0.22
    let couplet = if top_matches.len() >= 2
        && (top_matches[0].probability - top_matches[1].probability) < 0.22
    {
        scored[0]
            .1
            .sympatric_couplet
            .map(ToString::to_string)
            .or_else(|| Some(format!("{}/{}", top_matches[0].code, top_matches[1].code)))
    } else {
        None
    };

    (top_matches, couplet)
}
