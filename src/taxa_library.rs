//! Grounded Taxonomic Acoustic Key & Gaussian-Mahalanobis Likelihood Classifier
//! covering 10 Chiropteran (Bat) species and 10 Avian (Bird) species with NABat/BBL
//! 4-letter codes, sympatric ambiguity couplets, and canonical primary literature URLs.

use crate::call_extractor::{CallShapeTopology, DetectedCallEvent, TaxonDomain};
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SpeciesAcousticProfile {
    pub code: &'static str,
    pub common_name: &'static str,
    pub scientific_name: &'static str,
    pub family: &'static str,
    pub domain: TaxonDomain,
    pub region_note: &'static str,
    /// Characteristic (`Fc`) or Center frequency (`kHz`) mean and SD.
    pub fc_mean_khz: f64,
    pub fc_sd_khz: f64,
    /// Maximum frequency (`Fmax` / `HiFreq`, `kHz`) mean and SD.
    pub fmax_mean_khz: f64,
    pub fmax_sd_khz: f64,
    /// Minimum frequency (`Fmin` / `LoFreq`, `kHz`) mean and SD.
    pub fmin_mean_khz: f64,
    pub fmin_sd_khz: f64,
    /// Typical call/syllable duration (`ms`) mean and SD.
    pub dur_mean_ms: f64,
    pub dur_sd_ms: f64,
    /// Characteristic body slope (`kHz/ms`) expected magnitude.
    pub char_slope_khz_ms: f64,
    pub preferred_topology: CallShapeTopology,
    pub expect_strong_2nd_harmonic: bool,
    pub sympatric_couplet: Option<&'static str>,
    pub citation_label: &'static str,
    pub citation_url: &'static str,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TaxonMatch {
    pub code: String,
    pub common_name: String,
    pub scientific_name: String,
    pub probability: f64,
    pub mahalanobis_d2: f64,
    pub citation_url: String,
}

